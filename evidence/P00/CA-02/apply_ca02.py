"""Apply contract amendment CA-02 to the canonical store schema and resync copies. Idempotence guarded."""
import json, sys
root = sys.argv[1]
def dump(o): return json.dumps(o, indent=2, ensure_ascii=False) + "\n"
p = f"{root}/schemas/workbench-store-v1.2.schema.json"
s = json.load(open(p)); d = s["$defs"]
if "StreamRecord" in d: sys.exit("CA-02 already applied")
s["$comment"] += " Amendment CA-02 (2026-10-24, owner-approved F-2/F-3 from P00-T05): descendant cleanup, child signal status, stream reader state; see 05_Database_Data_Schema.md section 23. Version-identifier handling pending owner confirmation."
tr = d["TerminationRecord"]
tr["$comment"] = "reason is the primary supervisor trigger and is never overwritten by later descendant cleanup; descendant_cleanup records that action separately. 'descendant_cleanup' as reason means the child exited on its own and cleanup was the only supervisor action. process_tree_exited is null when undeterminable."
tr["properties"]["reason"]["enum"].append("descendant_cleanup")
tr["properties"]["descendant_cleanup"] = {"$ref": "#/$defs/DescendantCleanup"}
tr["required"].append("descendant_cleanup")
d["DescendantCleanup"] = {
    "$comment": "Supervisor action against members of the tool's process group that remained after the direct child exited or was terminated. Does not cover descendants that left the group/session.",
    "type": "object", "additionalProperties": False,
    "properties": {
        "performed": {"type": "boolean"},
        "method": {"type": "string", "enum": ["not_required", "graceful", "forced", "failed"]},
        "leftover_live_count": {"anyOf": [{"type": "integer", "minimum": 0}, {"type": "null"}]}},
    "required": ["performed", "method", "leftover_live_count"]}
d["StreamRecord"] = {
    "$comment": "Per-stream reader outcome. bytes_consumed = bytes read by the supervisor; bytes_retained = bytes kept in memory for parsing/evidence. Child-generated bytes beyond what was consumed are unknown. not_applicable = no reader existed (e.g. spawn failure); counts are then null.",
    "type": "object", "additionalProperties": False,
    "properties": {
        "state": {"type": "string", "enum": ["not_applicable", "complete", "truncated", "reader_timeout"]},
        "bytes_consumed": {"anyOf": [{"type": "integer", "minimum": 0}, {"type": "null"}]},
        "bytes_retained": {"anyOf": [{"type": "integer", "minimum": 0}, {"type": "null"}]}},
    "required": ["state", "bytes_consumed", "bytes_retained"]}
wc = d["WrapperControl"]; props = {}
for k, v in wc["properties"].items():
    props[k] = v
    if k == "tool_exit_code":
        props["tool_term_signal"] = {"anyOf": [{"type": "integer", "minimum": 1}, {"type": "null"}]}
    if k == "termination":
        props["output_streams"] = {"type": "object", "additionalProperties": False,
            "properties": {"stdout": {"$ref": "#/$defs/StreamRecord"}, "stderr": {"$ref": "#/$defs/StreamRecord"}},
            "required": ["stdout", "stderr"]}
wc["properties"] = props
r = wc["required"]; r.insert(r.index("tool_exit_code") + 1, "tool_term_signal"); r.insert(r.index("termination") + 1, "output_streams")
ck = d["Check"]; props = {}
for k, v in ck["properties"].items():
    props[k] = v
    if k == "exit_code":
        props["term_signal"] = {"anyOf": [{"type": "integer", "minimum": 1}, {"type": "null"}]}
ck["properties"] = props
r = ck["required"]; r.insert(r.index("exit_code") + 1, "term_signal")
open(p, "w").write(dump(s))
for name, ref, title in [("wrapper-request", "WrapperRequest", "PWT WrapperRequest v1.0"), ("wrapper-control", "WrapperControl", "PWT WrapperControl v1.0")]:
    wp = f"{root}/schemas/{name}-v1.0.schema.json"
    w = json.load(open(wp))
    open(wp, "w").write(dump({"$schema": w["$schema"], "$comment": s["$comment"], "title": title, "$ref": f"#/$defs/{ref}", "$defs": s["$defs"]}))
mp = f"{root}/05_Database_Data_Schema.md"; lines = open(mp).read().split("\n")
st = lines.index("```json", 100); en = lines.index("```", st + 1)
lines[st + 1:en] = dump(s).rstrip("\n").split("\n")
open(mp, "w").write("\n".join(lines))
print("CA-02 applied and synced")
