_INVISIBLE = {0x200B, 0x200E, 0x200F, 0x202A, 0x202B, 0x202C, 0x202D, 0x202E, 0x2066, 0x2067, 0x2068, 0x2069, 0xFEFF}


def escape_str(s: str, keep_newlines: bool = True) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if keep_newlines and ch in "\n\t":
            out.append(ch)
        elif o < 0x20 or 0x7F <= o <= 0x9F or o in _INVISIBLE:
            out.append(f"<U+{o:04X}>")
        else:
            out.append(ch)
    return "".join(out)


def _escape(b: bytes) -> str:
    return escape_str(b.decode("utf-8", "replace"))


_MD_SPECIAL = set("\\`*_{}[]()#+-.!|~")


def md_escape(s) -> str:
    """Text -> one-line Markdown-inert text: control/bidi characters escaped (newlines too), HTML-significant
    characters as entities, Markdown-significant characters backslash-escaped."""
    s = escape_str(str(s), keep_newlines=False)
    out = []
    for ch in s:
        if ch == "&":
            out.append("&amp;")
        elif ch == "<":
            out.append("&lt;")
        elif ch == ">":
            out.append("&gt;")
        elif ch in _MD_SPECIAL:
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


class Redactor:
    """Detection and redaction of the run-time fake secrets (values, base64 forms, embedded markers)."""

    _RUN = re.compile(r"PWTFAKE[A-Za-z0-9+/=]*")
    WIN, STRIDE = 12, 4      # component fragments of >= WIN + STRIDE - 1 = 15 characters are always detected
    MIN_COMPONENT_PARTIAL = 4  # a trailing component prefix shorter than this is not treated as a partial

    def __init__(self, canaries: dict[str, str], markers: dict[str, str], components: dict[str, str] | None = None):
        self.markers = markers
        self.full: list[tuple[str, str]] = []          # (pattern, label), longest first
        self.detect: dict[str, list[bytes]] = {}
        for cid, v in canaries.items():
            b64 = base64.b64encode(v.encode()).decode()
            self.full += [(v, f"<canary:{cid}>"), (b64, f"<canary-b64:{cid}>")]
            self.detect[cid] = [v.encode(), b64.encode(), markers[cid].encode()]
        # H-3: registered secret-bearing components of multi-part synthetic fixtures (e.g. every PEM body line).
        self.windows: dict[str, str] = {}
        for cid, v in (components or {}).items():
            self.full.append((v, f"<synthetic:{cid}>"))
            pats = [v.encode()]
            if "\n" not in v:
                for i in range(0, len(v) - self.WIN + 1, self.STRIDE):
                    self.windows.setdefault(v[i:i + self.WIN], cid)
                    pats.append(v[i:i + self.WIN].encode())
            self.detect[cid] = pats
        self.full.sort(key=lambda pl: -len(pl[0]))
        comp_vals = set((components or {}).values())
        # (pattern, minimum trailing-prefix length): canaries/markers start with public prefixes, so any length
        # counts; registered random components count from MIN_COMPONENT_PARTIAL characters.
        self.prefix_sources = [(p, self.MIN_COMPONENT_PARTIAL if p in comp_vals else 1) for p, _ in self.full if "\n" not in p] \
            + [(m, 1) for m in markers.values()]
        self.maxlen = max(len(p) for p, _ in self.prefix_sources)

    def _marker_label(self, m: re.Match) -> str:
        run = m.group(0)
        for cid, mk in sorted(self.markers.items(), key=lambda kv: -len(kv[1])):
            if run.startswith(mk):
                return f"<canary-partial:{cid}>"
        return "<canary-partial:?>"

    def text(self, s: str) -> str:
        for p, label in self.full:
            if p in s:
                s = s.replace(p, label)
        # Every canary puts its marker before its random part, so any surviving fragment that reveals
        # random characters starts with a marker: redact the marker and the alphabet run after it.
        s = self._RUN.sub(self._marker_label, s)
        # Fragments of registered components: redact the whole base64-alphabet run around any known window.
        if self.windows:
            def frag(m: re.Match) -> str:
                run = m.group(0)
                for w, cid in self.windows.items():
                    if w in run:
                        return f"<synthetic-fragment:{cid}>"
                return run
            s = self._B64RUN.sub(frag, s)
        return s

    _B64RUN = re.compile(r"[A-Za-z0-9+/=]{%d,}" % WIN)

    def _tail_prefix_len(self, s) -> int:
        best = 0
        for p, mn in self.prefix_sources:
            pp = p if isinstance(s, str) else p.encode()
            for k in range(min(len(pp) - 1, len(s)), max(best, mn - 1), -1):
                if s.endswith(pp[:k]):
                    best = k
                    break
        return best

    def trim_tail(self, s):
        """Remove a trailing proper prefix of any pattern (a canary cut by a truncation boundary)."""
        k = self._tail_prefix_len(s)
        return (s[:-k], True) if k else (s, False)

    def hits(self, data: bytes) -> list[str]:
        return sorted(cid for cid, pats in self.detect.items() if any(p in data for p in pats))

    def excerpt(self, data: bytes, limit: int = EXCERPT) -> tuple[str, bool]:
        s = self.text(_escape(data))
        cut = len(s) > limit
        if cut:
            s = self.trim_tail(s[:limit])[0]
        if self.hits(s.encode()) or "PWTFAKE" in s:
            return "<excerpt withheld: residual registered synthetic material>", cut
        return s, cut


class _StreamScan:
    def __init__(self, red: Redactor):
        self.red, self.tail, self.found = red, b"", set()

    def feed(self, chunk: bytes) -> None:
        buf = self.tail + chunk
        self.found.update(self.red.hits(buf))
        self.tail = buf[-(self.red.maxlen - 1):]


# ---------------------------------------------------------------------- namespace / loopback helpers
_SIOCGIFFLAGS, _SIOCSIFFLAGS, _IFF_UP = 0x8913, 0x8914, 0x1


def lo_flags() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
        r = fcntl.ioctl(s, _SIOCGIFFLAGS, struct.pack("16sH22x", b"lo", 0))
    return struct.unpack("16sH22x", r)[1]


def set_lo(up: bool) -> None:
    f = lo_flags()
    new = (f | _IFF_UP) if up else (f & ~_IFF_UP)
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
        fcntl.ioctl(s, _SIOCSIFFLAGS, struct.pack("16sH22x", b"lo", new))


def lo_is_up() -> bool:
    return bool(lo_flags() & _IFF_UP)


def tcp_listeners() -> list[str]:
    out = []
    for f in ("/proc/net/tcp", "/proc/net/tcp6"):
        try:
            lines = Path(f).read_text().splitlines()[1:]
        except OSError:
            continue
        out += [l.split()[1] for l in lines if l.split()[3] == "0A"]
    return out


def connect_ok(port: int, timeout: float = 2.0) -> str:
    try:
        with socket.create_connection(("127.0.0.1", port), timeout=timeout):
            return "connected"
    except OSError as e:
        return f"failed errno {e.errno}"


class LoopbackSchemaServer:
    """Stdlib HTTP server on 127.0.0.1 inside the private network namespace, serving one controlled
    directory. Brings `lo` up on entry and down on exit; shutdown, socket close and thread join are in
    finally paths; records every request path. Usage:
        with LoopbackSchemaServer(dir) as srv: ...; srv.stop_server(); ...  (lo stays up until exit)"""

    def __init__(self, directory: Path, join_timeout: float = 5.0):
        self.directory, self.join_timeout = Path(directory), join_timeout
        self.requests: list[str] = []
        self.obs: dict = {"lo_up_before": None}
        self._srv = self._thread = None
        self.port = None

    def __enter__(self):
        self.obs["lo_up_before"] = lo_is_up()
        set_lo(True)
        self.obs["lo_up_after_enable"] = lo_is_up()
        reqs = self.requests

        class H(http.server.SimpleHTTPRequestHandler):
            def log_request(self, code="-", size="-"):
                reqs.append(f"{self.command} {self.path[:200]} {getattr(code, 'value', code)}")

            def log_message(self, *a, **k):
                pass

        try:
            self._srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(H, directory=str(self.directory)))
            self._srv.daemon_threads = True
            self.port = self._srv.server_address[1]
            self.obs["endpoint"] = f"http://127.0.0.1:{self.port}/"
            self._thread = threading.Thread(target=self._srv.serve_forever, kwargs={"poll_interval": 0.1}, daemon=True)
            self._thread.start()
        except BaseException:
            self._teardown()
            raise
        return self

    def stop_server(self) -> None:
        if self._srv is not None:
            try:
                self._srv.shutdown()
            finally:
                self._srv.server_close()
                if self._thread is not None:
                    self._thread.join(self.join_timeout)
                self.obs["thread_alive_after_stop"] = bool(self._thread and self._thread.is_alive())
                self.obs["listeners_after_stop"] = tcp_listeners()
                self.obs["requests_while_serving"] = list(self.requests)
                self._srv = None

    def _teardown(self) -> None:
        try:
            self.stop_server()
        finally:
            set_lo(False)
            self.obs["lo_up_after_exit"] = lo_is_up()
            self.obs["listeners_after_exit"] = tcp_listeners()

    def __exit__(self, *exc):
        self._teardown()
        return False


def reap_orphans(exclude: set[int] = frozenset()) -> int:
    """As PID 1 of the namespace, reap zombie children reparented to us (never `exclude`)."""
    n = 0
    me = os.getpid()
    for d in Path("/proc").iterdir():
        if not d.name.isdigit() or int(d.name) in exclude:
            continue
        try:
            stat = (d / "stat").read_text()
        except OSError:
            continue
        rest = stat[stat.rfind(")") + 2:].split()
        if rest[0] == "Z" and int(rest[1]) == me:
            try:
                if os.waitpid(int(d.name), os.WNOHANG)[0]:
                    n += 1
            except ChildProcessError:
                pass
    return n


class Ctx:
    """Per-tool context handed to `cases(ctx)`."""

    def __init__(self, root: Path, tool: str, canaries: dict[str, str], markers: dict[str, str],
                 components: dict[str, str] | None = None):
        self.root = root
        self.tool = tool
        self.bin = str(TOOLS[tool])
        self.canaries = canaries          # canary ID -> raw value (memory only)
        self.components = components or {}  # H-3 synthetic fixture components (memory only)
        self.red = Redactor(canaries, markers, self.components)
        self.rlimit_as = RLIMIT_AS_BY_TOOL.get(tool, RLIMIT_AS_DEFAULT)
        self.runs: list[dict] = []
        self.hyps: list[dict] = []
        self.notes: list[dict] = []
        self.work = root / "work" / tool
        self.work.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------ helpers
    def case_dir(self, case_id: str) -> Path:
        """Fresh empty directory for one case (never reused)."""
        d = self.work / case_id
        if d.exists():
            shutil.rmtree(d)
        (d / "home").mkdir(parents=True)
        (d / "xdg-config").mkdir()
        (d / "xdg-cache").mkdir()
        (d / "tmp").mkdir()
        (d / "repo").mkdir()
        return d

    def sanitise(self, s: str) -> str:
        return self.red.text(escape_str(s))

    def clean(self, v):
        """Recursively sanitise and control-escape every string in a note value."""
        if isinstance(v, str):
            return self.sanitise(v)
        if isinstance(v, bytes):
            return self.red.text(_escape(v))
        if isinstance(v, dict):
            return {self.clean(str(k)): self.clean(x) for k, x in v.items()}
        if isinstance(v, (list, tuple, set)):
            return [self.clean(x) for x in (sorted(v, key=str) if isinstance(v, set) else v)]
        return v

    def scan(self, data: bytes) -> list[str]:
        """Canary IDs present in `data` (by raw value, base64 form or embedded marker)."""
        return self.red.hits(data)

    def markers(self) -> list[str]:
        """Execution markers under this tool's own work directory (other tools' markers are not this tool's)."""
        return sorted(p.name for p in self.work.rglob("PWT_EXECUTED_*"))

    # ------------------------------------------------------------------ run
    def _spawn_and_collect(self, argv, cwd, env, timeout, rlimit_as):
        lim = rlimit_as

        def pre():
            resource.setrlimit(resource.RLIMIT_AS, (lim, lim))

        info = {"timed_out": False, "term_sent": False, "kill_sent": False, "kill_reason": None,
                "group_killed_after_exit": False, "pipes_force_closed": False, "child_reaped": False}
        caps = {"out": bytearray(), "err": bytearray()}
        totals = {"out": 0, "err": 0}
        scans = {"out": _StreamScan(self.red), "err": _StreamScan(self.red)}
        t0 = time.monotonic()
        p = subprocess.Popen(argv, cwd=cwd, env=env, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE, start_new_session=True, preexec_fn=pre, close_fds=True)
        pgid = p.pid
        sel = selectors.DefaultSelector()
        files = {"out": p.stdout, "err": p.stderr}
        for name, f in files.items():
            os.set_blocking(f.fileno(), False)
            sel.register(f, selectors.EVENT_READ, name)
        open_n, status, ru = 2, None, None
        exited_at = term_at = kill_at = None

        def killpg(sig):
            try:
                os.killpg(pgid, sig)
                return True
            except ProcessLookupError:
                return False

        try:
            while open_n or status is None:
                now = time.monotonic()
                if info["kill_sent"] and status is None and now - kill_at >= DRAIN_S + 5:
                    info["abandoned_unreaped"] = True      # SIGKILL did not end the direct child (should not happen)
                    break
                if status is None:
                    pid, st, r = os.wait4(p.pid, os.WNOHANG)
                    if pid:
                        status, ru, exited_at = st, r, now
                        info["child_reaped"] = True
                if status is None and not info["timed_out"] and now - t0 >= timeout:
                    info["timed_out"], info["term_sent"], term_at = True, True, now
                    killpg(signal.SIGTERM)
                if not info["kill_sent"]:
                    if info["timed_out"] and status is None and now - term_at >= TERM_GRACE_S:
                        info["kill_sent"], info["kill_reason"], kill_at = True, "timeout escalation", now
                        killpg(signal.SIGKILL)
                    elif status is not None and open_n and now - exited_at >= LINGER_S:
                        info["kill_sent"], info["kill_reason"], kill_at = True, "pipes held after child exit", now
                        info["group_killed_after_exit"] = killpg(signal.SIGKILL)
                    elif info["timed_out"] and status is not None and open_n:
                        info["kill_sent"], info["kill_reason"], kill_at = True, "pipes held after timed-out child exit", now
                        killpg(signal.SIGKILL)
                if info["kill_sent"] and open_n and status is not None and now - kill_at >= DRAIN_S:
                    for key in list(sel.get_map().values()):
                        sel.unregister(key.fileobj)
                        key.fileobj.close()
                    open_n, info["pipes_force_closed"] = 0, True
                    break
                if not open_n:
                    time.sleep(0.02)
                    continue
                for key, _ in sel.select(timeout=0.05):
                    name = key.data
                    try:
                        chunk = os.read(key.fileobj.fileno(), READ_CHUNK)
                    except BlockingIOError:
                        continue
                    if not chunk:
                        sel.unregister(key.fileobj)
                        key.fileobj.close()
                        open_n -= 1
                        continue
                    totals[name] += len(chunk)
                    scans[name].feed(chunk)
                    room = OUTPUT_CAP - len(caps[name])
                    if room > 0:
                        caps[name] += chunk[:room]
        finally:
            if status is None:
                killpg(signal.SIGKILL)
            for key in list(sel.get_map().values()):
                sel.unregister(key.fileobj)
                key.fileobj.close()
            sel.close()
        # Any group members left (e.g. closed their pipes but kept running): remove them.
        if killpg(0):
            info["group_killed_after_exit"] = killpg(signal.SIGKILL) or info["group_killed_after_exit"]
        if status is None:
            for _ in range(50):
                pid, st, r = os.wait4(p.pid, os.WNOHANG)
                if pid:
                    status, ru = st, r
                    info["child_reaped"] = True
                    break
                time.sleep(0.1)
        p.returncode = os.waitstatus_to_exitcode(status) if status is not None else None
        wall = time.monotonic() - t0
        reap_orphans(exclude={os.getpid()})
        retained = {}
        trimmed = {}
        for name in ("out", "err"):
            b = bytes(caps[name])
            if totals[name] > OUTPUT_CAP:
                b, trimmed[name] = self.red.trim_tail(b)
            else:
                trimmed[name] = False
            retained[name] = b
        return p.returncode, retained, totals, scans, trimmed, info, wall, ru

    def run(self, case_id: str, argv: list[str], cwd: Path, *, purpose: str, fixtures: list[str],
            extra_env: dict[str, str] | None = None, timeout: int = DEFAULT_TIMEOUT,
            scan_files: list[Path] | None = None, parse_json: bool = False, rlimit_as: int | None = None) -> dict:
        """Run the tool once. Returns the record; record['_stdout'] / ['_stderr'] / ['_json'] are
        raw-in-memory helpers for the case code (retained part, trailing partial canary removed) and are
        stripped before persistence. `rlimit_as` overrides the per-tool limit (harness self-test only)."""
        case_root = cwd if (cwd / "home").exists() else cwd.parent
        env = {
            "PATH": "/usr/bin:/bin",
            "LANG": "C.UTF-8",
            "HOME": str(case_root / "home"),
            "XDG_CONFIG_HOME": str(case_root / "xdg-config"),
            "XDG_CACHE_HOME": str(case_root / "xdg-cache"),
            "TMPDIR": str(case_root / "tmp"),
        }
        if extra_env:
            env.update(extra_env)
        lim = rlimit_as if rlimit_as is not None else self.rlimit_as
        before = {p for p in case_root.rglob("*")}
        markers_before = set(self.markers())
        spawn_error = None
        try:
            rc, retained, totals, scans, trimmed, info, wall, ru = self._spawn_and_collect(argv, cwd, env, timeout, lim)
        except OSError as e:
            spawn_error = f"{type(e).__name__} errno {e.errno}"
            rc, retained, totals, trimmed, info, wall, ru = None, {"out": b"", "err": b""}, {"out": 0, "err": 0}, {"out": False, "err": False}, {}, 0.0, None
            scans = {"out": _StreamScan(self.red), "err": _StreamScan(self.red)}
        out, err = retained["out"], retained["err"]
        after = {p for p in case_root.rglob("*")}
        created = sorted(str(p.relative_to(case_root)) for p in after - before if p.is_file())
        file_hits = {}
        for f in scan_files or []:
            if f.exists() and f.is_file():
                file_hits[str(f.relative_to(case_root))] = self.scan(f.read_bytes()[:FILE_SCAN_CAP])
        so_ex, so_cut = self.red.excerpt(out)
        se_ex, se_cut = self.red.excerpt(err)
        rec = {
            "case": case_id,
            "tool": self.tool,
            "purpose": purpose,
            "fixtures": fixtures,
            "argv": [self.sanitise(a) for a in argv],
            "cwd": str(cwd.relative_to(self.root)),
            "env_names": sorted(env),
            "network": "private netns",
            "rlimit_as_bytes": lim,
            "spawn_error": spawn_error,
            "exit": rc if rc is None or rc >= 0 else None,
            "signal": -rc if (rc is not None and rc < 0) else None,
            "timed_out": info.get("timed_out", False),
            "cleanup": {k: v for k, v in info.items() if k != "timed_out"},
            "wall_ms": int(wall * 1000),
            "child_maxrss_kib": getattr(ru, "ru_maxrss", None),
            "stdout_bytes": totals["out"],
            "stderr_bytes": totals["err"],
            "stdout_truncated_for_analysis": totals["out"] > OUTPUT_CAP,
            "stderr_truncated_for_analysis": totals["err"] > OUTPUT_CAP,
            "retained_trailing_partial_removed": {"stdout": trimmed["out"], "stderr": trimmed["err"]},
            "canary_in_stdout": sorted(scans["out"].found),
            "canary_in_stderr": sorted(scans["err"].found),
            "canary_in_files": file_hits,
            "files_created": [self.sanitise(c) for c in created][:50],
            "new_execution_markers": sorted(set(self.markers()) - markers_before),
            "network_attempt_signals": sorted({m.group(0).lower()[:60] for m in NET_PATTERNS.finditer(self.sanitise(_escape(err)) + self.sanitise(_escape(out)))})[:10],
            "stdout_excerpt": so_ex,
            "stderr_excerpt": se_ex,
            "excerpt_truncated": {"stdout": so_cut, "stderr": se_cut},
        }
        rec["_stdout"], rec["_stderr"] = out, err
        if parse_json:
            try:
                rec["_json"] = json.loads(out.decode("utf-8", "replace"))
                rec["json_parse"] = "ok"
            except ValueError as e:
                rec["_json"] = None
                rec["json_parse"] = f"failed: {str(e)[:80]}"
        self.runs.append(rec)
        return rec

    # ------------------------------------------------------------------ outcomes
    def hyp(self, hid: str, outcome: str, detail: str, runs: list[str]) -> None:
        """Record one hypothesis outcome. `runs` are the case IDs that are the evidence."""
        assert outcome in OUTCOMES, outcome
        self.hyps.append({"hypothesis": hid, "outcome": outcome, "detail": self.sanitise(detail), "evidence_runs": runs})

    def note(self, key: str, value) -> None:
        """Record a contract-sheet fact (e.g. JSON field names, exit map, flags used)."""
        self.notes.append({"key": self.sanitise(key), "value": self.clean(value)})

    def export(self) -> dict:
        runs = [{k: v for k, v in r.items() if not k.startswith("_")} for r in self.runs]
        return {"tool": self.tool, "binary": self.bin, "rlimit_as_bytes": self.rlimit_as, "runs": runs,
                "hypotheses": self.hyps, "notes": self.notes}
