"""P00-T09 shared spike harness (Opus-owned shared contract; stdlib only, Python >= 3.12).

Spike code, not application code. Every tool invocation goes through `Ctx.run`, which:
- builds the child environment from an allowlist (scratch HOME/XDG/TMPDIR, no keys, tokens or proxies);
- starts the child in its own session/process group with a per-tool RLIMIT_AS (gitleaks 16 GiB,
  owner-approved 2026-10-24; all other tools 4 GiB, unchanged);
- reads stdout/stderr itself with bounded retention, a wall-clock timeout and bounded cleanup:
  timeout -> SIGTERM to the invocation's process group -> SIGKILL after a grace period; if the direct
  child exits while inherited pipes stay open, the group is killed after a linger period; pipe draining
  after that is bounded and our pipe ends are then closed. Descendants that leave the process group
  (setsid/setpgid) are NOT contained by this; only the PID namespace teardown ends them;
- scans the full streams (not only the retained part) and named output files for fake-secret canaries
  (by value, base64 form and embedded marker), and the spike root for execution markers (`PWT_EXECUTED_*`);
- records only sanitised excerpts: redaction happens before truncation, a trailing partial canary at a
  truncation boundary is removed, control characters are escaped.

Raw tool outputs never leave the scratch root. Case modules (`cases_<tool>.py`) call `ctx.run`
and `ctx.hyp` and must classify outcomes honestly: confirmed / refuted /
partially confirmed (conditions) / not testable (reason) / observed.

The canary guard detects only the run-time fake secrets generated by `fixtures.gen_canaries`; it is
not a detector for arbitrary real secrets.
"""

