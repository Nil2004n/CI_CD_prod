package pwt.launcher;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import pwt.infrastructure.SqliteStore;

/**
 * PWT-owned project context pointer: {@code <repository>/.pwt/context.md}.
 *
 * <p>The file tells the PWT agent (plain file reads, no MCP/SQL) where the
 * repository's scan journal lives. It contains only the repository ID,
 * root, absolute journal path, and local data/application locations plus a
 * short read instruction — never findings, credentials, or executable
 * instructions.
 *
 * <p>The file is PWT-owned and marked as such ({@link #MARKER}). Writers
 * never overwrite unrelated content: an existing file without the marker
 * is left untouched.
 */
public final class ProjectContext {

    /** Marker proving PWT ownership; writers refuse files that lack it. */
    public static final String MARKER = "PWT-OWNED";

    private ProjectContext() {
    }

    /**
     * Writes or refreshes the context pointer. Returns the path written,
     * or {@code null} when an existing non-PWT file was left untouched.
     */
    public static Path writeIfManaged(Path root, SqliteStore.RepositoryRow repo,
            Path journalPath, Path appRoot, Path dataDir) throws IOException {
        Path dir = root.resolve(".pwt");
        Path file = dir.resolve("context.md");
        if (Files.exists(file)) {
            String current = Files.readString(file, StandardCharsets.UTF_8);
            if (!current.contains(MARKER)) {
                return null;
            }
        } else {
            Files.createDirectories(dir);
        }
        StringBuilder out = new StringBuilder();
        out.append("<!-- ").append(MARKER).append(": project context pointer. Safe to delete; ")
                .append("regenerated by `pwt repo-add` / `make setup-opencode`. Do not edit below this line. -->\n");
        out.append("# PWT project context — ").append(repo.displayName()).append('\n');
        out.append("- Repository ID: `").append(repo.id()).append("`\n");
        out.append("- Repository root: `").append(root.toAbsolutePath().normalize()).append("`\n");
        out.append("- Scan journal: `").append(journalPath.toAbsolutePath().normalize()).append("`\n");
        out.append("- PWT data directory: `").append(dataDir.toAbsolutePath().normalize()).append("`\n");
        out.append("- PWT application root: `").append(appRoot.toAbsolutePath().normalize()).append("`\n");
        out.append("Read the scan journal above for assessment questions "
                + "(\"What does the latest scan say?\"). Its latest completed section is the current "
                + "evidence; older sections are history. If the journal file is absent, say \"No PWT "
                + "assessment is available for this project. Open /pwt and run its first scan in the "
                + "dashboard.\" and scan nothing yourself; do not "
                + "fall back to MCP, SQL, or shell inspection. Paths on this page are local-machine-specific.\n");
        Files.writeString(file, out.toString(), StandardCharsets.UTF_8);
        return file;
    }
}
