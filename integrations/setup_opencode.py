#!/usr/bin/env python3
"""Install/merge project-local OpenCode PWT configuration.

Usage: setup_opencode.py --project-dir DIR [--data-dir DIR]
                         [--allow-analysis 0|1] [--launcher PATH]

One shared database: --data-dir defaults to <application-root>/.pwt-data
(the directory holding the root Makefile). Pass --data-dir explicitly only
for an intentionally separate installation; it is printed, never generated
per repository. Requires an ABSOLUTE path (relative paths are rejected).

- Merges the `pwt` MCP server entry into <project>/opencode.json, preserving
  every unrelated key/server.
- Dashboard-only scanning: this installer NEVER writes --allow-scans into an
  OpenCode entry. A legacy --allow-scans flag on the managed `pwt` entry is
  removed (reported); unrelated entries are untouched. The deprecated
  --allow-scans 0|1 CLI flag is accepted for backward compatibility but
  ignored (warns when 1 is requested).
- ALLOW_ANALYSIS / --allow-analysis-writes (fresh default: denied).
- Installs the native PWT command plugin into <project>/.opencode/plugins/pwt
  (no model-interpreted /pwt markdown command is installed; remove any old one).
- Copies the PWT conversation reference (documentation only).
- Prints the effective mode and data directory.
- Never touches global OpenCode configuration in project mode.

With --global (no --project-dir needed), writes the `pwt` entry to the
user-global ~/.config/opencode/opencode.json instead, so MCP tools are
available in any directory. The global entry is unscoped (explicit local
admin); every call is still repository-scoped server-side, and per-project
entries override it. Fresh global entries default to read-only; pass
--allow-analysis 1 explicitly to enable analysis writes. Scan permission is
never written here: scans run only from the dashboard.
"""
import argparse
import json
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP_ROOT = HERE.parent
DEFAULT_DATA_DIR = APP_ROOT / ".pwt-data"


def load_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        print(f"setup-opencode: refusing to modify {path}: not parseable JSON ({exc})",
              file=sys.stderr)
        print("setup-opencode: back it up, or remove it, then rerun", file=sys.stderr)
        sys.exit(2)


def sanitize_name(display):
    """Mirror of JournalWriter.sanitizeName: file-safe display name."""
    clean = []
    last_dash = True
    for ch in (display or "").strip():
        ok = (ch.isascii() and ch.isalnum()) or ch in "._-"
        if ok:
            clean.append(ch)
            last_dash = False
        elif not last_dash and clean:
            clean.append("-")
            last_dash = True
        if len(clean) >= 48:
            break
    name = "".join(clean).strip("-.")
    return name or "repo"


def ensure_context_pointer(project, data_dir):
    """Backstop for `pwt repo-add` (the primary context writer): if the
    project root is registered in the data directory's store, make sure its
    .pwt/context.md pointer exists. Read-only against the database; never
    overwrites a non-PWT file."""
    try:
        import sqlite3
        db = data_dir / "pwt.db"
        if not db.is_file():
            return
        canonical = str(project.resolve())
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        try:
            row = con.execute(
                "SELECT id, display_name FROM repositories WHERE canonical_root=?",
                (canonical,)).fetchone()
        finally:
            con.close()
        if row is None:
            print("setup-opencode: project not registered yet; open /pwt and run "
                  "its first scan in the dashboard (writes .pwt/context.md; "
                  "`make repo-add` remains for headless admin).",
                  file=sys.stderr)
            return
        repo_id, display = row
        journal = None
        for candidate in sorted((data_dir / "reports").glob(f"*--{repo_id}.md")):
            journal = candidate
            break
        if journal is None:
            journal = data_dir / "reports" / f"{sanitize_name(display)}--{repo_id}.md"
        pointer = project / ".pwt" / "context.md"
        if pointer.is_file() and "PWT-OWNED" not in pointer.read_text(encoding="utf-8"):
            print(f"setup-opencode: kept existing non-PWT {pointer} untouched",
                  file=sys.stderr)
            return
        pointer.parent.mkdir(parents=True, exist_ok=True)
        pointer.write_text(
            "<!-- PWT-OWNED: project context pointer. Safe to delete; regenerated by "
            "`pwt repo-add` / `make setup-opencode`. Do not edit below this line. -->\n"
            f"# PWT project context — {display}\n"
            f"- Repository ID: `{repo_id}`\n"
            f"- Repository root: `{canonical}`\n"
            f"- Scan journal: `{journal}`\n"
            f"- PWT data directory: `{data_dir}`\n"
            f"- PWT application root: `{HERE.parent}`\n"
            "Read the scan journal above for assessment questions "
            "(\"What does the latest scan say?\"). Its latest completed section is the current "
            "evidence; older sections are history. If the journal file is absent, say \"No PWT "
            "assessment is available for this project. Open /pwt and run its first scan in the "
            "dashboard.\" and scan nothing yourself; do not "
            "fall back to MCP, SQL, or shell inspection. Paths on this page are local-machine-specific.\n",
            encoding="utf-8")
        print(f"setup-opencode: context pointer: {pointer}")
    except Exception as exc:
        print(f"setup-opencode: WARNING: context pointer not written: {exc}", file=sys.stderr)


def build_entry(existing, launcher, data_dir, allow_scans, allow_analysis):
    """Build the pwt MCP server entry, preserving unrelated keys and an
    explicitly configured timeout. Dashboard-only scanning: --allow-scans is
    NEVER written by this installer (legacy flag is stripped and reported).
    allow_analysis: "1" adds --allow-analysis-writes, "0" removes, "" preserves
    an existing flag (fresh entries default to denied)."""
    if not isinstance(existing, dict):
        existing = {}
    if allow_scans == "1":
        print("setup-opencode: WARNING: --allow-scans 1 is ignored: "
              "OpenCode never scans; use the dashboard (/pwt).", file=sys.stderr)
    command = [str(launcher), "--data-dir", str(data_dir)]
    old_cmd = existing.get("command", [])
    if isinstance(old_cmd, list) and "--allow-scans" in old_cmd:
        print("setup-opencode: removed legacy --allow-scans from the managed "
              "`pwt` entry (dashboard-only scanning).")
    if allow_analysis == "1":
        command.append("--allow-analysis-writes")
    elif allow_analysis == "0":
        pass
    else:
        if isinstance(old_cmd, list) and "--allow-analysis-writes" in old_cmd:
            command.append("--allow-analysis-writes")
    entry = dict(existing)
    entry["type"] = "local"
    entry["command"] = command
    # Bound tool-call waits: the 12h client default would park a wedged
    # session "forever". Every PWT call returns in milliseconds (scans run
    # server-side and are polled), so 5 minutes can only trigger on a stuck
    # transport, which then fails fast instead of hanging. Preserve an
    # explicitly configured timeout.
    timeouts = entry.get("timeout")
    if not isinstance(timeouts, dict):
        timeouts = {}
    timeouts.setdefault("execution", 300000)
    entry["timeout"] = timeouts
    return entry


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-dir", default="")
    parser.add_argument("--global", dest="global_scope", action="store_true",
                        help="write the pwt entry to the user-global OpenCode config instead of a project")
    parser.add_argument("--data-dir", default=str(DEFAULT_DATA_DIR))
    parser.add_argument("--allow-scans", default="", choices=["", "0", "1"])
    parser.add_argument("--allow-analysis", default="", choices=["", "0", "1"])
    parser.add_argument("--launcher", default=str(HERE / "pwt-mcp-stdio.sh"))
    parser.add_argument("--plugin-src", default=str(HERE / "opencode-plugin"))
    parser.add_argument("--instructions-src", default=str(HERE / "pwt-conversation.md"))
    args = parser.parse_args()

    launcher = Path(args.launcher)
    if not launcher.is_file():
        print(f"setup-opencode: launcher missing: {launcher}", file=sys.stderr)
        return 2
    data_dir = Path(args.data_dir)
    if not data_dir.is_absolute():
        print(f"setup-opencode: --data-dir must be absolute: {args.data_dir}", file=sys.stderr)
        return 2
    try:
        data_dir.mkdir(parents=True, exist_ok=True)
        try:
            os.chmod(data_dir, 0o700)
        except OSError:
            pass  # non-POSIX filesystem: umask applies
    except OSError as exc:
        print(f"setup-opencode: cannot create data dir {data_dir}: {exc}", file=sys.stderr)
        return 2

    if args.global_scope:
        return setup_global(args, launcher, data_dir)

    project = Path(args.project_dir)
    if not project.is_dir():
        print(f"setup-opencode: project dir missing: {project}", file=sys.stderr)
        return 2

    config_path = project / "opencode.json"
    config = load_json(config_path)
    if not isinstance(config, dict):
        print(f"setup-opencode: refusing to modify {config_path}: top level is not an object",
              file=sys.stderr)
        return 2
    servers = config.setdefault("mcp", {}).setdefault("servers", {})
    entry = build_entry(servers.get("pwt"), launcher, data_dir,
                        args.allow_scans, args.allow_analysis)
    servers["pwt"] = entry
    config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")

    # Native command plugin (replaces any model-interpreted /pwt command).
    plugin_src = Path(args.plugin_src)
    plugin_dir = project / ".opencode" / "plugins" / "pwt"
    if plugin_src.is_dir():
        if plugin_dir.exists():
            shutil.rmtree(plugin_dir)
        shutil.copytree(plugin_src, plugin_dir,
                         ignore=shutil.ignore_patterns("__pycache__", ".git", "agent-pwt.md",
                                                      "pwt-ask.md"))
        # agent-pwt.md and pwt-ask.md are GLOBAL definitions; they ship only via
        # make install-opencode and never land in a project plugin dir.
        for stale in [project / ".opencode" / "commands" / "pwt.md",
                      project / ".opencode" / "command" / "pwt.md"]:
            if stale.is_file():
                stale.unlink()
                print(f"setup-opencode: removed superseded prompt command: {stale}")
    else:
        print(f"setup-opencode: WARNING: native plugin source missing: {plugin_src}", file=sys.stderr)
    shutil.copyfile(args.instructions_src, project / ".opencode" / "pwt-conversation.md")
    ensure_context_pointer(project, data_dir)

    print(f"setup-opencode: pwt MCP server configured ({describe_mode(entry)})")
    print(f"setup-opencode: data directory: {data_dir}")
    print(f"setup-opencode: native commands: {[c.name for c in sorted((project / '.opencode' / 'plugins' / 'pwt').glob('*')) if c.suffix in ('.ts', '.js')]}")
    return 0


def describe_mode(entry):
    command = entry.get("command", [])
    mode = "read-only (dashboard-only scanning)"
    if "--allow-scans" in command:
        mode = "NON-COMPLIANT: scan flag still present (--allow-scans)"
    if "--allow-analysis-writes" in command:
        mode += " + analysis writes (--allow-analysis-writes)"
    return mode


def setup_global(args, launcher, data_dir):
    """Write the pwt entry to the user-global OpenCode config so MCP tools
    are available in any directory (explicit local-admin mode: unscoped
    server, per-call repository enforcement). Merges; never touches other
    servers or keys. Fresh global entries default to read-only; pass
    --allow-scans 1 / --allow-analysis 1 explicitly to enable writes."""
    home = Path.home()
    config_path = home / ".config" / "opencode" / "opencode.json"
    config = load_json(config_path)
    if not isinstance(config, dict):
        print(f"setup-opencode: refusing to modify {config_path}: top level is not an object",
              file=sys.stderr)
        return 2
    mcp = config.get("mcp")
    if not isinstance(mcp, dict):
        print(f"setup-opencode: refusing to modify {config_path}: 'mcp' is not an object",
              file=sys.stderr)
        return 2
    servers = mcp.setdefault("servers", {})
    if not isinstance(servers, dict):
        print(f"setup-opencode: refusing to modify {config_path}: 'mcp.servers' is not an object",
              file=sys.stderr)
        return 2
    entry = build_entry(servers.get("pwt"), launcher, data_dir,
                        args.allow_scans, args.allow_analysis)
    servers["pwt"] = entry
    config_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    print(f"setup-opencode: global pwt MCP server configured ({describe_mode(entry)})")
    print(f"setup-opencode: global config: {config_path}")
    print("setup-opencode: note: global entry is unscoped (explicit local admin);")
    print("setup-opencode: every call is still repository-scoped server-side,")
    print("setup-opencode: and per-project entries override this one when present.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
